-- ============ grade-review-1：复核材料与申请流转变分离 ============
-- 口径：复核申请的流转（提交/结论/关闭）与材料阅读分开处理。材料文件进入 evops-base 即留档，
--       按进入时间排列；附件版本替换不删旧版，旧版保留摘要（文件名/大小/哈希/替换原因/钟点）标 SUPERSEDED。
--       阅读单独记阅读记录，不影响申请状态；窗口关闭只禁止新受理，历史申请与材料仍可查看/阅读。
--       学员凭 X-Self-Code 只能读本人资料；审核岗改结论状态必须写明依据；
--       通知回执挂回原申请；导出一律不带出内部批注。

-- ============ 复核材料（一份材料一条主记录：当前版本指针 + 模块/版本/状态） ============
CREATE TABLE IF NOT EXISTS t_review_material (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id BIGINT NOT NULL,
    batch_id BIGINT NOT NULL,
    registration_id BIGINT NOT NULL,
    reg_no VARCHAR(40) NOT NULL,
    name VARCHAR(64) NOT NULL,
    -- 材料标题（如 身份证扫描件、成绩复核申请表）
    title VARCHAR(128) NOT NULL,
    -- DOC 书证 / PHOTO 照片 / FORM 申请表 / OTHER 其他
    material_type VARCHAR(16) NOT NULL DEFAULT 'DOC',
    -- 模块当前状态（取当前版本）：ACTIVE 在档可阅读 / SUPERSEDED 已被新版本替换（仅留摘要，可查不可读正文）
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    current_version INT NOT NULL DEFAULT 1,
    -- 内部批注：仅内部管理视图可见，学员视图与任何导出都不带出
    internal_annotation VARCHAR(1024),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_review_material_review_title UNIQUE (review_id, title)
);
CREATE INDEX IF NOT EXISTS idx_review_material_review ON t_review_material (review_id);
CREATE INDEX IF NOT EXISTS idx_review_material_batch ON t_review_material (batch_id);
CREATE INDEX IF NOT EXISTS idx_review_material_reg ON t_review_material (registration_id);

-- ============ 复核材料版本（只追加：登记 / 替换各一版；旧版留摘要，永不删除） ============
CREATE TABLE IF NOT EXISTS t_review_material_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_id BIGINT NOT NULL,
    review_id BIGINT NOT NULL,
    version_no INT NOT NULL,
    -- ACTIVE 当前版（文件可阅读） / SUPERSEDED 旧版（正文引用随替换失效，仅留摘要可查）
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    -- 文件引用（路径/对象存储键）与摘要指纹（SHA-256）；旧版字段保留作"留摘要"
    file_ref VARCHAR(255),
    content_hash VARCHAR(64),
    -- 文本材料正文（附件类可空）
    content CLOB,
    -- 文件大小（字节）与原始文件名，旧版留摘要时一并保留
    file_size BIGINT,
    original_filename VARCHAR(255),
    -- 摘要说明（可空，默认按文件名/大小/哈希生成）
    digest_summary VARCHAR(1024),
    -- REGISTER 随材料进入留档 / REPLACE 附件版本替换
    change_type VARCHAR(16) NOT NULL DEFAULT 'REGISTER',
    change_reason VARCHAR(512),
    operator VARCHAR(64),
    entered_at TIMESTAMP NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_review_material_version_no UNIQUE (material_id, version_no)
);
CREATE INDEX IF NOT EXISTS idx_review_mv_material ON t_review_material_version (material_id);
